def _ensemble_results_to_rows(results, switch_names: list[str]) -> list[dict]:
    rows = []
    for r in results:
        row = {
            "preset_name": r.preset_name,
            "acceptance_rule": r.acceptance_rule,
            "threshold": r.threshold,
            "n_accepted": r.n_accepted,
            "n_evaluated": r.n_evaluated,
            "acceptance_rate": round(r.acceptance_rate, 4),
            "D_RACH": r.D_RACH,
            "R_RACH": r.R_RACH,
            "K": r.K,
        }
        for sw in switch_names:
            row[f"CA_{sw}"] = r.ca_j.get(sw, float("nan"))
        rows.append(row)
    return rows


def _rows_to_ensemble_results(rows: list[dict]):
    """Reconstruct EnsembleResult objects from an ensemble_results.csv."""
    from causal_model.ensemble import EnsembleResult
    results = []
    for r in rows:
        ca_j = {k[3:]: _to_float(v) for k, v in r.items() if k.startswith("CA_")}
        results.append(EnsembleResult(
            preset_name=r.get("preset_name", ""),
            acceptance_rule=r.get("acceptance_rule", ""),
            threshold=_to_float(r.get("threshold")),
            n_accepted=int(_to_float(r.get("n_accepted")) or 0),
            n_evaluated=int(_to_float(r.get("n_evaluated")) or 0),
            D_RACH=_to_float(r.get("D_RACH")),
            R_RACH=_to_float(r.get("R_RACH")),
            ca_j=ca_j,
            K=int(_to_float(r.get("K")) or len(ca_j)),
        ))
    return results


def _write_ensemble_csv(results, switch_names, ensemble_dir: Path) -> Path:
    ensemble_dir.mkdir(parents=True, exist_ok=True)
    rows = _ensemble_results_to_rows(results, switch_names)
    path = ensemble_dir / "ensemble_results.csv"
    if rows:
        with path.open("w", newline="", encoding="utf-8") as f:
            w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
            w.writeheader()
            w.writerows(rows)
    return path


def run_ensemble_for_report(n_attempts: int = 150, seed: int = 42):
    """Run a proxy-backend ensemble scan for the report (all presets × rules)."""
    from causal_model.ensemble import run_ensemble
    from causal_model.switch_inference import GRADIENT_THRESH_MAP, CAMPANULA_SWITCHES
    from causal_model.parameter_sampling import predefined_tradeoff_presets

    presets = list(predefined_tradeoff_presets().keys())
    rules   = ["weighted_lax", "relaxed_0.83", "relaxed_0.67"]
    rules   = [r for r in rules if r in GRADIENT_THRESH_MAP] or list(GRADIENT_THRESH_MAP.keys())[:3]
    return run_ensemble(
        presets=presets, acceptance_rules=rules,
        switches=CAMPANULA_SWITCHES, n_attempts=n_attempts,
        seed=seed, backend="proxy",
    )


def load_or_run_ensemble(ensemble_dir: Path, run: bool, n_attempts: int, seed: int):
    """Return EnsembleResult list, running a fresh scan if needed.

    Reads ``ensemble_results.csv`` unless ``run`` is True or the file is missing.
    """
    from causal_model.switch_inference import CAMPANULA_SWITCHES
    switch_names = [sw.name for sw in CAMPANULA_SWITCHES]
    csv_path = ensemble_dir / "ensemble_results.csv"

    if not run and csv_path.exists():
        rows = _read_csv(csv_path)
        if rows:
            return _rows_to_ensemble_results(rows), switch_names

    results = run_ensemble_for_report(n_attempts=n_attempts, seed=seed)
    _write_ensemble_csv(results, switch_names, ensemble_dir)
    return results, switch_names


def summarize_ensemble(results, switch_names: list[str]) -> dict:
    from causal_model.ensemble import (
        select_best_ensemble_setting,
        classify_switch_robustness,
        sensitivity_range,
    )
    if not results:
        return {"available": False}

    sel = select_best_ensemble_setting(results, min_accepted=20, min_acceptance_rate=0.02)
    robustness = classify_switch_robustness(results)
    sens = sensitivity_range(results)
    return {
        "available": True,
        "n_configs": len(results),
        "selection": sel,
        "robustness": robustness,
        "sensitivity_range": sens,
        "robust_switches": [r.switch for r in robustness if r.is_robust],
        "sensitive_switches": [r.switch for r in robustness if not r.is_robust],
        "switch_names": switch_names,
    }


def ensemble_summary_md(ens: dict) -> str:
    lines = ["# Ensemble sensitivity summary", ""]
    lines.append(f"> {EPISTEMIC_CAUTION}")
    lines.append("")
    if not ens.get("available"):
        lines.append("_No ensemble results available._")
        return "\n".join(lines) + "\n"

    sel = ens["selection"]
    best = sel.best
    lines += [f"Configurations scanned: **{ens['n_configs']}**", ""]
    if best is not None:
        lines += [
            "## Best (ensemble-selected) setting", "",
            f"- preset: `{best.preset_name}`",
            f"- acceptance_rule: `{best.acceptance_rule}`",
            f"- n_accepted: {best.n_accepted}",
            f"- acceptance_rate: {_fmt(best.acceptance_rate)}",
            f"- R_RACH: {_fmt(best.R_RACH)}",
            f"- D_RACH: {_fmt(best.D_RACH)}",
            f"- passed_stability_filters: {sel.passed_filters}",
            "",
            f"_{sel.rationale}_", "",
        ]

    lines += ["## Robust vs prior/ε-sensitive switches", "",
              "| switch | mean_CA_j | sensitivity_range | robust | call |",
              "|---|---|---|---|---|"]
    for r in ens["robustness"]:
        lines.append(
            f"| {r.switch} | {_fmt(r.mean_ca_j)} | {_fmt(r.sensitivity_range)} | "
            f"{'yes' if r.is_robust else 'no'} | {r.call} |"
        )
    lines += ["",
              f"- Robust switches: {', '.join(ens['robust_switches']) or '(none)'}",
              f"- Sensitive (prior/ε) switches: "
              f"{', '.join(ens['sensitive_switches']) or '(none)'}",
              ""]
    return "\n".join(lines) + "\n"


