def results_summary_md(bench: dict, ens: dict) -> str:
    lines = ["# RACH results summary (manuscript-safe)", ""]
    lines.append(f"> {EPISTEMIC_CAUTION}")
    lines.append("")
    lines += [
        "This document separates two distinct claims:", "",
        "1. **Synthetic known-truth recovery** — can the inference pipeline "
        "recover a fixed switch state from data generated by the same simulator? "
        "This is a self-consistency check.",
        "2. **Empirical ensemble inference** — across prior presets and ABC ε "
        "thresholds, which switches give stable (robust) admissibility verdicts, "
        "and which are prior/ε sensitive? This estimates admissibility, not truth.",
        "",
    ]

    if bench.get("available"):
        o = bench["overall"]
        weakest = bench["switch_quality"][0]["switch"] if bench["switch_quality"] else None
        lines += [
            "## Known-truth recovery", "",
            f"Across {bench['n_cases']} synthetic cases, mean recovery accuracy was "
            f"{_fmt(o['accuracy'])} (F1 {_fmt(o['f1'])}, mean absolute CA error "
            f"{_fmt(o['mean_abs_ca_error'])}). "
            + (f"The weakest-recovered switch was `{weakest}`. " if weakest else "")
            + "These figures describe self-consistency under the specified "
            "simulator and do not establish ecological causation.",
            "",
        ]
    else:
        lines += ["## Known-truth recovery", "",
                  "_No benchmark outputs available._", ""]

    if ens.get("available"):
        sel = ens["selection"]
        best = sel.best
        robust = ens["robust_switches"]
        sensitive = ens["sensitive_switches"]
        rec = ""
        if best is not None:
            rec = (f"The ensemble-selected setting (`{best.preset_name}` + "
                   f"`{best.acceptance_rule}`) gave R_RACH {_fmt(best.R_RACH)} and "
                   f"D_RACH {_fmt(best.D_RACH)}. ")
        lines += [
            "## Empirical ensemble inference", "",
            rec
            + (f"Switches robust to prior/ε choice: "
               f"{', '.join(robust) or '(none)'}. "
               f"Prior/ε-sensitive switches requiring additional observations: "
               f"{', '.join(sensitive) or '(none)'}. ")
            + "Sensitive switches are the targets recommended by next-observation "
              "value (NOV); they are not interpreted as resolved mechanisms.",
            "",
            "RACH reproduced the observed syndrome within the admissible region, "
            "but admissibility is not identification: a robust verdict means the "
            "conclusion is stable across reasonable analytic choices, not that the "
            "switch is the true ecological cause.",
            "",
        ]
    else:
        lines += ["## Empirical ensemble inference", "",
                  "_No ensemble results available._", ""]

    return "\n".join(lines) + "\n"


