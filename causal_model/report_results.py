"""Generate fixed benchmark and ensemble report artifacts (issue #26).

Turns known-truth benchmark and ensemble-sensitivity outputs into stable
manuscript-safe summary documents and figures.

EPISTEMIC NOTE
--------------
The known-truth benchmark is a *specified-simulator recovery* test: it measures
whether RACH ABC inference recovers a fixed switch state when synthetic data are
generated by the same simulator.  It is NOT proof of real-world causal truth.
Empirical ensemble inference on the Campanula data is reported separately, and
the reports never claim that a recovered or admissible switch is the true
ecological mechanism.

Inputs
------
* ``outputs/known_truth_benchmark/`` — CSVs from
  ``python -m causal_model.known_truth_benchmark``
  (known_truth_summary.csv, known_truth_cases.csv, recovery_by_noise.csv,
  recovery_by_n_attempts.csv).
* ``outputs/ensemble/ensemble_results.csv`` — ensemble scan
  (auto-generated here if missing, or via ``--run-ensemble``).

Outputs
-------
* ``outputs/reports/benchmark_summary.md``
* ``outputs/reports/ensemble_summary.md``
* ``outputs/reports/results_summary.md``
* ``outputs/reports/figures/*.png`` (matplotlib; skipped if unavailable)

Usage
-----
    # one command — auto-runs small benchmark/ensemble if their CSVs are missing
    python -m causal_model.report_results

    # use existing benchmark outputs, regenerate the ensemble scan
    python -m causal_model.report_results --run-ensemble

    python -m causal_model.report_results \
        --benchmark-dir outputs/known_truth_benchmark \
        --ensemble-dir outputs/ensemble \
        --output-dir outputs/reports
"""
from __future__ import annotations

import argparse
import csv
import math
import sys
from pathlib import Path

EPISTEMIC_CAUTION = (
    "This is a specified-simulator recovery benchmark, not proof of real-world "
    "causal truth. Synthetic known-truth recovery measures self-consistency of "
    "the inference pipeline; empirical ensemble inference estimates which "
    "mechanisms remain admissible, not which is true."
)


# ---------------------------------------------------------------------------
# CSV helpers (no pandas dependency)
# ---------------------------------------------------------------------------

def _read_csv(path: Path) -> list[dict]:
    if not path.exists():
        return []
    with path.open(newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def _to_float(v) -> float:
    try:
        if v is None or v == "":
            return float("nan")
        return float(v)
    except (TypeError, ValueError):
        return float("nan")


def _mean(vals) -> float:
    xs = [v for v in vals if not (isinstance(v, float) and math.isnan(v))]
    return sum(xs) / len(xs) if xs else float("nan")


def _fmt(v, nd: int = 3) -> str:
    if isinstance(v, float) and math.isnan(v):
        return "n/a"
    if isinstance(v, float):
        return f"{v:.{nd}f}"
    return str(v)


