def generate_reports(
    benchmark_dir: Path,
    ensemble_dir: Path,
    output_dir: Path,
    run_ensemble: bool = False,
    run_benchmark: bool = False,
    ensemble_n_attempts: int = 150,
    benchmark_n_attempts: int = 80,
    seed: int = 42,
) -> dict[str, Path]:
    """Generate all report markdowns and figures. Returns {name: path}."""
    # Auto-run a small benchmark if its CSVs are missing (one-command UX).
    if run_benchmark or not (benchmark_dir / "known_truth_summary.csv").exists():
        print("  Running quick known-truth benchmark (preview settings)…")
        from causal_model.known_truth_benchmark import (
            run_benchmark as _rb, save_outputs, TRUE_SWITCH_STATES,
        )
        subset = [s for s in TRUE_SWITCH_STATES
                  if s[0] in {"all_off", "S1_only", "S2_only", "S1_S2", "S1_S2_S3"}]
        res = _rb(true_states=subset, noise_rates=(0.0, 0.1, 0.2),
                  n_attempts=benchmark_n_attempts, seed=seed, verbose=False)
        save_outputs(res, benchmark_dir)

    bench = summarize_benchmark(benchmark_dir)

    results, switch_names = load_or_run_ensemble(
        ensemble_dir, run=run_ensemble, n_attempts=ensemble_n_attempts, seed=seed)
    ens = summarize_ensemble(results, switch_names)
    ens["_results"] = results   # for figure generation

    output_dir.mkdir(parents=True, exist_ok=True)
    fig_dir = output_dir / "figures"

    written: dict[str, Path] = {}
    (output_dir / "benchmark_summary.md").write_text(benchmark_summary_md(bench), encoding="utf-8")
    written["benchmark_summary.md"] = output_dir / "benchmark_summary.md"
    (output_dir / "ensemble_summary.md").write_text(ensemble_summary_md(ens), encoding="utf-8")
    written["ensemble_summary.md"] = output_dir / "ensemble_summary.md"
    (output_dir / "results_summary.md").write_text(results_summary_md(bench, ens), encoding="utf-8")
    written["results_summary.md"] = output_dir / "results_summary.md"

    figs = generate_figures(bench, ens, fig_dir)
    for p in figs:
        written[f"figures/{p.name}"] = p
    return written


def _build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        description="Generate RACH benchmark and ensemble report artifacts (issue #26).",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    p.add_argument("--benchmark-dir", default="outputs/known_truth_benchmark")
    p.add_argument("--ensemble-dir", default="outputs/ensemble")
    p.add_argument("--output-dir", default="outputs/reports")
    p.add_argument("--run-ensemble", action="store_true",
                   help="Force a fresh ensemble scan even if ensemble_results.csv exists.")
    p.add_argument("--run-benchmark", action="store_true",
                   help="Force a fresh (quick) known-truth benchmark run.")
    p.add_argument("--ensemble-n-attempts", type=int, default=150)
    p.add_argument("--benchmark-n-attempts", type=int, default=80)
    p.add_argument("--seed", type=int, default=42)
    return p


def main(argv: list[str] | None = None) -> int:
    args = _build_parser().parse_args(argv)
    print("=" * 60)
    print("RACH report generator (issue #26)")
    print("=" * 60)
    written = generate_reports(
        benchmark_dir=Path(args.benchmark_dir),
        ensemble_dir=Path(args.ensemble_dir),
        output_dir=Path(args.output_dir),
        run_ensemble=args.run_ensemble,
        run_benchmark=args.run_benchmark,
        ensemble_n_attempts=args.ensemble_n_attempts,
        benchmark_n_attempts=args.benchmark_n_attempts,
        seed=args.seed,
    )
    print("\nWritten:")
