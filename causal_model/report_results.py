def generate_figures(bench: dict, ens: dict, fig_dir: Path) -> list[Path]:
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except Exception:
        print("  matplotlib unavailable — skipping figures.", file=sys.stderr)
        return []

    fig_dir.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []

    def _save(fig, name):
        p = fig_dir / name
        fig.tight_layout()
        fig.savefig(p, dpi=120)
        plt.close(fig)
        written.append(p)

    # benchmark_accuracy_by_noise.png
    if bench.get("available") and bench["by_noise"]:
        rows = bench["by_noise"]
        x = [_to_float(r.get("noise_rate")) for r in rows]
        acc = [_to_float(r.get("mean_accuracy")) for r in rows]
        f1 = [_to_float(r.get("mean_f1")) for r in rows]
        fig, ax = plt.subplots(figsize=(5, 3.2))
        ax.plot(x, acc, "o-", label="accuracy")
        ax.plot(x, f1, "s--", label="F1")
        ax.set_xlabel("noise_rate"); ax.set_ylabel("score")
        ax.set_title("Known-truth recovery by noise rate"); ax.set_ylim(0, 1.02)
        ax.legend()
        _save(fig, "benchmark_accuracy_by_noise.png")

    # benchmark_f1_by_n_attempts.png
    if bench.get("available") and bench["by_n_attempts"] and len(bench["by_n_attempts"]) > 1:
        rows = bench["by_n_attempts"]
        x = [_to_float(r.get("n_attempts")) for r in rows]
        f1 = [_to_float(r.get("mean_f1")) for r in rows]
        fig, ax = plt.subplots(figsize=(5, 3.2))
        ax.plot(x, f1, "o-")
        ax.set_xlabel("n_attempts"); ax.set_ylabel("mean F1")
        ax.set_title("F1 vs n_attempts (convergence)"); ax.set_ylim(0, 1.02)
        _save(fig, "benchmark_f1_by_n_attempts.png")

    # ensemble figures
    if ens.get("available"):
        from causal_model.ensemble import select_best_ensemble_setting  # noqa: F401
        results = ens.get("_results")
        switch_names = ens["switch_names"]

        if results:
            labels = [f"{r.preset_name[:6]}/{r.acceptance_rule[:8]}" for r in results]

            # ensemble_CA_j_by_config.png
            fig, ax = plt.subplots(figsize=(6, 3.4))
            for sw in switch_names:
                ax.plot(range(len(results)),
                        [r.ca_j.get(sw, float("nan")) for r in results],
                        "o-", label=sw[:12])
            ax.set_xticks(range(len(results)))
            ax.set_xticklabels(labels, rotation=45, ha="right", fontsize=7)
            ax.set_ylabel("CA_j"); ax.set_ylim(0, 1.02)
            ax.set_title("CA_j by configuration"); ax.legend(fontsize=6)
            _save(fig, "ensemble_CA_j_by_config.png")

            # R_RACH_by_config.png
            fig, ax = plt.subplots(figsize=(6, 3.2))
            ax.bar(range(len(results)), [r.R_RACH for r in results])
            ax.set_xticks(range(len(results)))
            ax.set_xticklabels(labels, rotation=45, ha="right", fontsize=7)
            ax.set_ylabel("R_RACH"); ax.set_title("R_RACH by configuration")
            _save(fig, "R_RACH_by_config.png")

        # sensitivity_range_by_switch.png
        sens = ens["sensitivity_range"]
        if sens:
            names = list(sens.keys())
            vals = [sens[n] for n in names]
            fig, ax = plt.subplots(figsize=(5.5, 3.2))
            colors = ["#d62728" if (not math.isnan(v) and v >= 0.20) else "#2ca02c"
                      for v in vals]
            ax.bar([n[:12] for n in names], vals, color=colors)
            ax.axhline(0.20, color="gray", ls="--", lw=1, label="sensitivity 0.20")
            ax.set_ylabel("max−min CA_j"); ax.set_title("Sensitivity range by switch")
            ax.tick_params(axis="x", labelrotation=30, labelsize=7); ax.legend(fontsize=7)
            _save(fig, "sensitivity_range_by_switch.png")

    return written


