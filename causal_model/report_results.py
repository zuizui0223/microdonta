def summarize_benchmark(bench_dir: Path) -> dict:
    """Aggregate known-truth benchmark CSVs into a summary dict.

    Returns a dict with overall means, per-noise / per-n_attempts breakdowns,
    and the weakest-recovered switches (lowest per-switch correct rate).
    Empty/missing inputs yield ``{"available": False}``.
    """
    summary_rows = _read_csv(bench_dir / "known_truth_summary.csv")
    case_rows    = _read_csv(bench_dir / "known_truth_cases.csv")
    by_noise     = _read_csv(bench_dir / "recovery_by_noise.csv")
    by_n_att     = _read_csv(bench_dir / "recovery_by_n_attempts.csv")

    if not summary_rows:
        return {"available": False}

    metrics = ["accuracy", "precision", "recall", "f1", "mean_abs_ca_error"]
    overall = {m: round(_mean([_to_float(r.get(m)) for r in summary_rows]), 4)
               for m in metrics}

    # Weakest-recovered switches: per-switch correct rate + mean abs CA error.
    per_switch: dict[str, dict] = {}
    for r in case_rows:
        name = r.get("switch_name", "")
        if not name:
            continue
        d = per_switch.setdefault(name, {"correct": [], "abs_err": []})
        d["correct"].append(1.0 if str(r.get("correct")).lower() == "true" else 0.0)
        d["abs_err"].append(_to_float(r.get("abs_ca_error")))
    switch_quality = [
        {
            "switch": name,
            "correct_rate": round(_mean(d["correct"]), 4),
            "mean_abs_ca_error": round(_mean(d["abs_err"]), 4),
        }
        for name, d in per_switch.items()
    ]
    switch_quality.sort(key=lambda x: (x["correct_rate"],
                                       -(_to_float(x["mean_abs_ca_error"]) or 0.0)))

    return {
        "available": True,
        "n_cases": len(summary_rows),
        "overall": overall,
        "by_noise": by_noise,
        "by_n_attempts": by_n_att,
        "switch_quality": switch_quality,
    }


def benchmark_summary_md(bench: dict) -> str:
    lines = ["# Known-truth recovery benchmark summary", ""]
    lines.append(f"> {EPISTEMIC_CAUTION}")
    lines.append("")
    if not bench.get("available"):
        lines.append("_No benchmark outputs found. Run "
                      "`python -m causal_model.known_truth_benchmark` first._")
        return "\n".join(lines) + "\n"

    o = bench["overall"]
    lines += [
        f"Cases analysed: **{bench['n_cases']}**", "",
        "## Overall recovery metrics", "",
        "| Metric | Mean |",
        "|---|---|",
        f"| Accuracy | {_fmt(o['accuracy'])} |",
        f"| Precision | {_fmt(o['precision'])} |",
        f"| Recall | {_fmt(o['recall'])} |",
        f"| F1 | {_fmt(o['f1'])} |",
        f"| Mean absolute CA error | {_fmt(o['mean_abs_ca_error'])} |",
        "",
    ]

    if bench["by_noise"]:
        lines += ["## Recovery by noise rate", "",
                  "| noise_rate | n_cases | accuracy | precision | recall | F1 | R_RACH |",
                  "|---|---|---|---|---|---|---|"]
        for r in bench["by_noise"]:
            lines.append(
                f"| {r.get('noise_rate','')} | {r.get('n_cases','')} | "
                f"{_fmt(_to_float(r.get('mean_accuracy')))} | "
                f"{_fmt(_to_float(r.get('mean_precision')))} | "
                f"{_fmt(_to_float(r.get('mean_recall')))} | "
                f"{_fmt(_to_float(r.get('mean_f1')))} | "
                f"{_fmt(_to_float(r.get('mean_R_RACH')))} |"
            )
        lines.append("")

    if bench["by_n_attempts"]:
        lines += ["## Recovery by n_attempts", "",
                  "| n_attempts | n_cases | accuracy | F1 | R_RACH |",
                  "|---|---|---|---|---|"]
        for r in bench["by_n_attempts"]:
            lines.append(
                f"| {r.get('n_attempts','')} | {r.get('n_cases','')} | "
                f"{_fmt(_to_float(r.get('mean_accuracy')))} | "
                f"{_fmt(_to_float(r.get('mean_f1')))} | "
                f"{_fmt(_to_float(r.get('mean_R_RACH')))} |"
            )
        lines.append("")

    if bench["switch_quality"]:
        lines += ["## Weakest-recovered switches", "",
                  "Ordered worst-first by per-switch correct rate.", "",
                  "| switch | correct_rate | mean_abs_ca_error |",
                  "|---|---|---|"]
        for s in bench["switch_quality"]:
            lines.append(f"| {s['switch']} | {_fmt(s['correct_rate'])} | "
                         f"{_fmt(s['mean_abs_ca_error'])} |")
        lines.append("")

    return "\n".join(lines) + "\n"


