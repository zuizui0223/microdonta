"""Known-truth recovery benchmark for RACH inference.

EPISTEMIC NOTE
--------------
This is a *specified-simulator recovery benchmark*.  It evaluates whether
RACH ABC inference can recover a fixed causal switch state s* when the
synthetic observations (y_obs) are generated by the *same* proxy model under
that known state.

This tests: "If the data-generating process were exactly the proxy model with
switch state s*, does RACH ABC inference recover s*?"

It does NOT test: "Is s* the true causal mechanism in nature."
The latter requires real ecological data and independent lines of evidence.

Workflow
--------
1.  Fix a true switch state s* (one of 8 representative combinations).
2.  Run proxy model under s* → synthetic pairwise relations y_obs^{synth}.
3.  Optionally inject noise (flip relations with probability noise_rate).
4.  Run RACH ABC inference against y_obs^{synth}.
5.  Compute CA_j for each switch.
6.  Threshold at 0.5: predicted_on = (CA_j >= 0.5).
7.  Compare predicted_on to true s*_j; report accuracy, precision, recall,
    F1, mean absolute CA error, D_RACH, R_RACH.

Usage
-----
    # Python API
    from causal_model.known_truth_benchmark import run_benchmark, save_outputs
    results = run_benchmark()
    save_outputs(results, "outputs/known_truth_benchmark")

    # CLI
    python -m causal_model.known_truth_benchmark
    python -m causal_model.known_truth_benchmark --n-attempts 100 --noise-rates 0.0,0.1
"""

