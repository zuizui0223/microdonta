def _safe_div(num: float, den: float) -> float:
    return num / den if den > 0 else float("nan")


def compute_case_metrics(
    accepted_rows: list[dict],
    true_state: dict[str, bool],
    switches,
) -> tuple[list[SwitchRecovery], dict]:
    """Compute per-switch CA_j and aggregate accuracy metrics.

    Returns
    -------
    (per_switch, aggregate_dict)
        per_switch    : list of SwitchRecovery (one per switch)
        aggregate_dict: accuracy, precision, recall, f1, mean_abs_ca_error
    """
    from causal_model.causal_admissibility import (
        causal_degeneracy,
        causal_resolvability,
    )

    n = len(accepted_rows)
    if n == 0:
        per = [
            SwitchRecovery(sw.name, true_state.get(sw.name, False),
                           float("nan"), False, False, float("nan"))
            for sw in switches
        ]
        agg = {
            "accuracy": float("nan"), "precision": float("nan"),
            "recall": float("nan"), "f1": float("nan"),
            "mean_abs_ca_error": float("nan"),
            "D_RACH": float("nan"), "R_RACH": float("nan"),
        }
        return per, agg

    per_switch: list[SwitchRecovery] = []
    for sw in switches:
        ca   = round(sum(1 for r in accepted_rows if r.get(sw.name)) / n, 4)
        pred = ca >= 0.5
        true = true_state.get(sw.name, False)
        per_switch.append(SwitchRecovery(
            switch_name=sw.name,
            true_on=true,
            ca_j=ca,
            predicted_on=pred,
            correct=(pred == true),
            abs_ca_error=round(abs(ca - float(true)), 4),
        ))

    # Confusion matrix across switches
    tp = sum(1 for s in per_switch if s.predicted_on and s.true_on)
    fp = sum(1 for s in per_switch if s.predicted_on and not s.true_on)
    tn = sum(1 for s in per_switch if not s.predicted_on and not s.true_on)
    fn = sum(1 for s in per_switch if not s.predicted_on and s.true_on)
    k  = len(per_switch)

    accuracy  = round(_safe_div(tp + tn, k), 4)
    precision = round(_safe_div(tp, tp + fp), 4)
    recall    = round(_safe_div(tp, tp + fn), 4)
    denom_f1  = 2 * tp + fp + fn
    f1        = round(_safe_div(2 * tp, denom_f1), 4)
    mae       = round(
        sum(s.abs_ca_error for s in per_switch if not math.isnan(s.abs_ca_error)) /
        max(sum(1 for s in per_switch if not math.isnan(s.abs_ca_error)), 1),
        4,
    )

    D = round(causal_degeneracy(accepted_rows, switches), 4)
    R = round(causal_resolvability(accepted_rows, switches), 4)

    agg = {
        "accuracy": accuracy, "precision": precision,
        "recall": recall, "f1": f1,
        "mean_abs_ca_error": mae,
        "D_RACH": D, "R_RACH": R,
    }
    return per_switch, agg


