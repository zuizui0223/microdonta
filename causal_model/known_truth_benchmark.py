def _as_row(v) -> str:
    """Serialize a value to a CSV-safe string."""
    if isinstance(v, float) and math.isnan(v):
        return ""
    if isinstance(v, bool):
        return str(v)
    return str(v)


def save_outputs(result: BenchmarkResult, output_dir: str | Path) -> dict[str, Path]:
    """Save benchmark results to CSV files.

    Files written
    -------------
    known_truth_cases.csv    : one row per (case × switch)
    known_truth_summary.csv  : one row per case (aggregate metrics)
    recovery_by_noise.csv    : metrics aggregated by noise_rate
    recovery_by_n_attempts.csv : metrics aggregated by n_attempts (sweep cases only)

    Returns
    -------
    dict mapping filename → Path of written file.
    """
    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)
    written: dict[str, Path] = {}

    # ---- known_truth_cases.csv ----
    cases_path = out / "known_truth_cases.csv"
    cases_fields = [
        "run_id", "true_state_label", "noise_rate", "n_attempts",
        "preset_name", "acceptance_rule",
        "generator_backend", "inference_backend", "backend_pair",
        "switch_name", "true_on", "ca_j", "predicted_on", "correct", "abs_ca_error",
        "n_accepted", "D_RACH", "R_RACH",
    ]
    with cases_path.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=cases_fields)
        w.writeheader()
        for c in result.cases:
            for s in c.per_switch:
                w.writerow({
                    "run_id":            c.run_id,
                    "true_state_label":  c.true_state_label,
                    "noise_rate":        c.noise_rate,
                    "n_attempts":        c.n_attempts,
                    "preset_name":       c.preset_name,
                    "acceptance_rule":   c.acceptance_rule,
                    "generator_backend": c.generator_backend,
                    "inference_backend": c.inference_backend,
                    "backend_pair":      c.backend_pair,
                    "switch_name":       s.switch_name,
                    "true_on":           s.true_on,
                    "ca_j":              _as_row(s.ca_j),
                    "predicted_on":      s.predicted_on,
                    "correct":           s.correct,
                    "abs_ca_error":      _as_row(s.abs_ca_error),
                    "n_accepted":        c.n_accepted,
                    "D_RACH":            _as_row(c.D_RACH),
                    "R_RACH":            _as_row(c.R_RACH),
                })
    written["known_truth_cases.csv"] = cases_path

    # ---- known_truth_summary.csv ----
    summary_path = out / "known_truth_summary.csv"
    summary_fields = [
        "run_id", "true_state_label", "noise_rate", "n_attempts",
        "preset_name", "acceptance_rule",
        "generator_backend", "inference_backend", "backend_pair",
        "n_accepted", "n_evaluated",
        "accuracy", "precision", "recall", "f1", "mean_abs_ca_error",
        "D_RACH", "R_RACH", "elapsed_s",
    ]
    with summary_path.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=summary_fields)
        w.writeheader()
        for c in result.cases:
            w.writerow({k: _as_row(getattr(c, k, "")) for k in summary_fields})
    written["known_truth_summary.csv"] = summary_path

    # ---- recovery_by_backend_pair.csv ----
    backend_path = out / "recovery_by_backend_pair.csv"
    _bp_groups: dict[str, list[BenchmarkCase]] = {}
    for c in result.cases:
        _bp_groups.setdefault(c.backend_pair, []).append(c)
    backend_fields = [
        "backend_pair", "generator_backend", "inference_backend", "n_cases",
        "mean_accuracy", "mean_precision", "mean_recall", "mean_f1",
        "mean_ca_error", "mean_R_RACH", "mean_D_RACH",
    ]
    with backend_path.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=backend_fields)
        w.writeheader()
        for bp, cases in sorted(_bp_groups.items()):
            def _bmean(attr):
                vals = [getattr(c, attr) for c in cases
                        if not math.isnan(getattr(c, attr))]
                return round(sum(vals) / len(vals), 4) if vals else float("nan")
            w.writerow({
                "backend_pair":      bp,
                "generator_backend": cases[0].generator_backend,
                "inference_backend": cases[0].inference_backend,
                "n_cases":           len(cases),
                "mean_accuracy":     _as_row(_bmean("accuracy")),
                "mean_precision":    _as_row(_bmean("precision")),
                "mean_recall":       _as_row(_bmean("recall")),
                "mean_f1":           _as_row(_bmean("f1")),
                "mean_ca_error":     _as_row(_bmean("mean_abs_ca_error")),
                "mean_R_RACH":       _as_row(_bmean("R_RACH")),
                "mean_D_RACH":       _as_row(_bmean("D_RACH")),
            })
    written["recovery_by_backend_pair.csv"] = backend_path

    # ---- recovery_by_noise.csv ----
    noise_path = out / "recovery_by_noise.csv"
    _noise_groups: dict[float, list[BenchmarkCase]] = {}
    for c in result.cases:
        _noise_groups.setdefault(c.noise_rate, []).append(c)

    noise_fields = [
        "noise_rate", "n_cases",
        "mean_accuracy", "mean_precision", "mean_recall", "mean_f1",
        "mean_ca_error", "mean_R_RACH", "mean_D_RACH",
    ]
    with noise_path.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=noise_fields)
        w.writeheader()
        for noise, cases in sorted(_noise_groups.items()):
            def _mean(attr):
                vals = [getattr(c, attr) for c in cases
                        if not math.isnan(getattr(c, attr))]
                return round(sum(vals) / len(vals), 4) if vals else float("nan")
            w.writerow({
                "noise_rate":     noise,
                "n_cases":        len(cases),
                "mean_accuracy":  _as_row(_mean("accuracy")),
                "mean_precision": _as_row(_mean("precision")),
                "mean_recall":    _as_row(_mean("recall")),
                "mean_f1":        _as_row(_mean("f1")),
                "mean_ca_error":  _as_row(_mean("mean_abs_ca_error")),
                "mean_R_RACH":    _as_row(_mean("R_RACH")),
                "mean_D_RACH":    _as_row(_mean("D_RACH")),
            })
    written["recovery_by_noise.csv"] = noise_path

    # ---- recovery_by_n_attempts.csv ----
    n_att_vals = sorted({c.n_attempts for c in result.cases})
    nattempts_path = out / "recovery_by_n_attempts.csv"
    nattempts_fields = [
        "n_attempts", "n_cases", "mean_accuracy", "mean_f1", "mean_R_RACH",
    ]
    with nattempts_path.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=nattempts_fields)
        w.writeheader()
        for n_att in n_att_vals:
            grp = [c for c in result.cases if c.n_attempts == n_att]
            def _mean2(attr):
                vals = [getattr(c, attr) for c in grp
                        if not math.isnan(getattr(c, attr))]
                return round(sum(vals) / len(vals), 4) if vals else float("nan")
            w.writerow({
                "n_attempts":  n_att,
                "n_cases":     len(grp),
                "mean_accuracy": _as_row(_mean2("accuracy")),
                "mean_f1":       _as_row(_mean2("f1")),
                "mean_R_RACH":   _as_row(_mean2("R_RACH")),
            })
    written["recovery_by_n_attempts.csv"] = nattempts_path

    return written


def make_figure(written: dict[str, Path], path: str) -> str | None:
    """Plot known-truth recovery from the written CSV aggregates.

    Panel A: mean accuracy and F1 vs injected pattern-noise rate.
    Panel B: convergence of accuracy / F1 / R_RACH with ABC draws
    (only drawn when an n_attempts sweep with >1 point is present).
    """
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except Exception:
        print("matplotlib unavailable — skipping figure.")
        return None
    import os

    def _read(name: str) -> list[dict[str, str]]:
        p = written.get(name)
        if p is None or not Path(p).exists():
            return []
        with open(p, newline="", encoding="utf-8") as f:
            return list(csv.DictReader(f))

    def _f(rows, key):
        out = []
        for r in rows:
            try:
                out.append(float(r[key]))
            except (KeyError, ValueError):
                out.append(float("nan"))
        return out

    noise = _read("recovery_by_noise.csv")
    sweep = _read("recovery_by_n_attempts.csv")
    has_sweep = len(sweep) > 1

    n_panels = 2 if has_sweep else 1
    fig, axes = plt.subplots(1, n_panels, figsize=(4.6 * n_panels, 3.8), squeeze=False)

    ax = axes[0][0]
    xs = _f(noise, "noise_rate")
    ax.plot(xs, _f(noise, "mean_accuracy"), "o-", label="accuracy", color="#2c7fb8")
    ax.plot(xs, _f(noise, "mean_f1"), "s--", label="F1", color="#d95f0e")
    ax.set_xlabel("pattern-noise rate")
    ax.set_ylabel("switch recovery")
    ax.set_ylim(0, 1.02)
    ax.legend(fontsize=8)
    ax.set_title("(A) Recovery vs noise\n(self-consistency under corrupted patterns)")

    if has_sweep:
        ax = axes[0][1]
        xs = _f(sweep, "n_attempts")
        ax.plot(xs, _f(sweep, "mean_accuracy"), "o-", label="accuracy", color="#2c7fb8")
        ax.plot(xs, _f(sweep, "mean_f1"), "s--", label="F1", color="#d95f0e")
        ax.plot(xs, _f(sweep, "mean_R_RACH"), "^:", label="R_RACH", color="#31a354")
        ax.set_xscale("log")
        ax.set_xlabel("ABC draws (log scale)")
        ax.set_ylim(0, 1.02)
        ax.legend(fontsize=8)
        ax.set_title("(B) Convergence with draws")

    fig.tight_layout()
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    fig.savefig(path, dpi=150)
    plt.close(fig)
    print(f"figure written: {path}")
    return path


