@dataclass
class SwitchRecovery:
    """Per-switch result for one benchmark case."""
    switch_name: str
    true_on: bool
    ca_j: float
    predicted_on: bool     # ca_j >= 0.5
    correct: bool          # predicted_on == true_on
    abs_ca_error: float    # |ca_j - float(true_on)|


@dataclass
class BenchmarkCase:
    """Results for one (true_state, noise_rate, n_attempts) combination."""
    run_id: str
    true_state_label: str
    true_state: dict[str, bool]
    noise_rate: float
    n_attempts: int
    preset_name: str
    acceptance_rule: str
    seed: int
    generator_backend: str = "proxy"   # how synthetic y_obs was generated
    inference_backend: str = "proxy"   # which backend ran RACH inference

    # --- filled after inference ---
    n_accepted: int = 0
    n_evaluated: int = 0
    elapsed_s: float = 0.0
    per_switch: list[SwitchRecovery] = field(default_factory=list)
    accuracy: float = float("nan")
    precision: float = float("nan")
    recall: float = float("nan")
    f1: float = float("nan")
    mean_abs_ca_error: float = float("nan")
    D_RACH: float = float("nan")
    R_RACH: float = float("nan")

