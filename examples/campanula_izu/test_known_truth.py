_SWITCH_NAMES = [sw.name for sw in CAMPANULA_SWITCHES]


def _make_synthetic_pattern_targets(
    true_switches: PathwaySwitches,
    n_points: int = 8,
) -> list[dict]:
    """Generate gradient pattern targets from a known switch configuration.

    Runs the proxy simulation with the given switches and derives gradient_slope
    / rank_order pattern targets from the outputs.  These synthetic targets are
    used as the ABC acceptance criterion in the known-truth validation.

    Returns 4 synthetic pattern targets:
      - nectar_guide decreasing with isolation (gradient_slope + rank_order)
      - selfing_rate  increasing with isolation (gradient_slope + rank_order)
    These mirror the real observed_patterns.csv but are derived synthetically.
    """
    from attraction_trait_model.parameters import ModelParameters
    outputs_dict, synth_env = simulate_campanula_isolation_gradient(
        true_switches, n_points=n_points
    )
    # Build gradient_slope targets from the simulated trend direction
    pops = sorted(outputs_dict.keys(), key=lambda p: synth_env.get(p, {}).get("distance_from_mainland", 0))
    guides = [outputs_dict[p].nectar_guide for p in pops]
    selfing = [outputs_dict[p].selfing_rate  for p in pops]

    # Compute slope signs
    def _slope_sign(vals):
        xs = list(range(len(vals)))
        n = len(xs)
        xm = sum(xs) / n
        ym = sum(vals) / n
        num = sum((x - xm) * (y - ym) for x, y in zip(xs, vals))
        den = sum((x - xm) ** 2 for x in xs)
        return (num / den) if den > 0 else 0.0

    guide_dir  = "negative" if _slope_sign(guides) < 0  else "positive"
    selfing_dir = "positive" if _slope_sign(selfing) > 0 else "negative"

    return [
        {"pattern": "synth_guide_slope",  "type": "gradient_slope", "variable": "nectar_guide",
         "predictor": "distance_from_mainland", "expected_direction": guide_dir,
         "weight": "1.0", "role": "response_target"},
        {"pattern": "synth_selfing_slope","type": "gradient_slope", "variable": "selfing_rate",
         "predictor": "distance_from_mainland", "expected_direction": selfing_dir,
         "weight": "1.0", "role": "response_target"},
        {"pattern": "synth_guide_rank",   "type": "rank_order",     "variable": "nectar_guide",
         "expected_direction": "decreasing" if guide_dir == "negative" else "increasing",
         "weight": "1.0", "role": "response_target"},
        {"pattern": "synth_selfing_rank", "type": "rank_order",     "variable": "selfing_rate",
         "expected_direction": "increasing" if selfing_dir == "positive" else "decreasing",
         "weight": "1.0", "role": "response_target"},
    ]


def _run_mini_inference(
    pattern_targets: list[dict],
    n_draws: int = 600,
    seed: int = 42,
    threshold: float = 0.75,
) -> list[dict]:
    """Run a lightweight ABC inference against given pattern targets.

    Returns accepted_rows (list of dicts with switch states).
    Useful for validation: provide synthetic targets, check if posterior
    peaks at the true switches.
    """
    preset = predefined_tradeoff_presets()["broad_prior"]
    param_sets = sample_valid_parameter_sets(preset, n=n_draws, seed=seed)
    rng = random.Random(seed + 1)

    accepted: list[dict] = []
    for ps in param_sets:
        model_params = param_set_to_model_parameters(ps)
        state = {sw.name: rng.random() < sw.prior_on_prob for sw in CAMPANULA_SWITCHES}
        pw_dict = {sw.name: sw.pathway_key for sw in CAMPANULA_SWITCHES}
        pw = PathwaySwitches(**{pw_dict[name]: float(v) for name, v in state.items()})

        try:
            outputs_dict, synth_env = simulate_campanula_isolation_gradient(
                pw, params=model_params, n_points=8
            )
            eval_result = evaluate_patterns(
                list(outputs_dict.values()), pattern_targets, synth_env
            )
        except Exception:
            continue

        if eval_result.weighted_match_rate >= threshold:
            row = {
                **state,
                "weighted_match_rate": eval_result.weighted_match_rate,
                "per_pattern_matched": {
                    m.pattern: (m.matched, m.weight) for m in eval_result.matches
                },
            }
            accepted.append(row)

    return accepted


