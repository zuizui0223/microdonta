"""Known-truth validation for RACH theory metrics.

These tests verify that RACH correctly recovers the true causal mechanisms
from synthetic data generated with a known switch configuration.

Validation design
-----------------
1. Generate synthetic gradient outputs from a known switch state (e.g., S1+S2 ON).
2. Build gradient pattern targets from those outputs (response_target patterns).
3. Run a lightweight ABC inference on those synthetic targets.
4. Verify that the posterior and identifiability metrics correctly favour the
   true switches over the false ones.

This is the ground-truth analogue of test_ecological_invariants.py:
  - test_ecological_invariants verifies that *real* Campanula gradient patterns
    are correctly generated by the right switches.
  - test_known_truth verifies that the *inference* correctly recovers those
    switches when the pattern targets are produced by a known mechanism.

Mathematical guarantee tested
------------------------------
If the true data-generating process is s* = {S1=ON, S2=ON}, then running RACH
on pattern targets generated by s* should yield:
  P(guide_attracts_bombus=ON | A_ε) > 0.5           (true switch identified)
  P(selfing_syndrome_active=ON | A_ε) > 0.5         (true switch identified)
  P(drift_drives_guide_loss=ON | A_ε) <= 0.5        (false switch not supported)
  I_j(true switches) > I_j(false switches)           (true switches more identifiable)

Run with:
    python examples/campanula_izu/test_known_truth.py
"""

